// Renders docs/PROTOCOL.md from src/protocol/index.ts. The TypeScript types are the single source:
// the compiler API reads the payload interfaces, their doc comments and the exported constants, so the
// doc cannot drift from the code. `pnpm docs:protocol` writes the file; test/protocol-doc.test.ts fails
// when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { ErrorCode, JOIN_ERROR_CODE, JOIN_ERROR_MESSAGE, RATE_LIMITS } from '../src/protocol/index';

const here = dirname(fileURLToPath(import.meta.url));
export const PROTOCOL_SOURCE = resolve(here, '../src/protocol/index.ts');
export const PROTOCOL_DOC = resolve(here, '../../../docs/PROTOCOL.md');

const oneLine = (text: string) => text.replace(/\s+/g, ' ').trim();
const cell = (text: string) => text.replace(/\|/g, '\\|');

function comment(node: ts.Node): string {
  const docs = (node as ts.Node & { jsDoc?: ts.JSDoc[] }).jsDoc;
  const last = docs?.[docs.length - 1];
  if (!last) return '';
  return oneLine(ts.getTextOfJSDocComment(last.comment) ?? '');
}

function members(source: ts.SourceFile, name: string) {
  const decl = source.statements.find(
    (s): s is ts.InterfaceDeclaration => ts.isInterfaceDeclaration(s) && s.name.text === name,
  );
  if (!decl) throw new Error(`interface ${name} not found in protocol/index.ts`);
  return decl.members.filter(ts.isPropertySignature).map((m) => ({
    name: m.name.getText(source).replace(/^'|'$/g, ''),
    type: oneLine(m.type?.getText(source) ?? 'unknown'),
    note: comment(m),
  }));
}

function declarationText(source: ts.SourceFile, name: string): string {
  const decl = source.statements.find(
    (s) =>
      (ts.isInterfaceDeclaration(s) || ts.isTypeAliasDeclaration(s)) &&
      (s as { name: ts.Identifier }).name.text === name,
  );
  if (!decl) throw new Error(`${name} not found in protocol/index.ts`);
  return decl.getText(source).replace(/^\s*\/\*\*[\s\S]*?\*\/\s*/, '');
}

export function renderProtocolDoc(): string {
  const text = readFileSync(PROTOCOL_SOURCE, 'utf8');
  const source = ts.createSourceFile(PROTOCOL_SOURCE, text, ts.ScriptTarget.ES2022, true);
  const c2s = members(source, 'C2SPayloads');
  const s2c = members(source, 'S2CPayloads');
  const limit = (type: string) => {
    const n = (RATE_LIMITS as Record<string, number | undefined>)[type];
    return n === undefined ? '-' : `${n}/s`;
  };
  const rows = (list: ReturnType<typeof members>, withLimit: boolean) =>
    list
      .map(
        (m) =>
          `| \`${m.name}\` | \`${cell(m.type)}\` | ${withLimit ? `${limit(m.name)} | ` : ''}${cell(m.note) || '-'} |`,
      )
      .join('\n');
  const named = [
    'TeamId',
    'TraitIds',
    'RoleRevealAbility',
    'RoleRevealItem',
    'RoleRevealTeammate',
    'RoleRevealPayload',
    'NightRevealEntry',
    'SwapLogEntry',
    'OnubGameOver',
    'JoinOptions',
  ]
    .map((n) => '```ts\n' + declarationText(source, n) + '\n```')
    .join('\n\n');
  const errors = Object.entries(ErrorCode)
    .map(([name, code]) => `| ${code} | \`${name}\` |`)
    .join('\n');

  return `# Wire protocol

> Generated by \`pnpm docs:protocol\` from \`packages/shared/src/protocol/index.ts\`. Do not edit by hand; a test fails when this file is stale. Design context: \`docs/ARCHITECTURE.md\` 5.5.

## Client to server

| Type | Payload | Limit | Notes |
|---|---|---|---|
${rows(c2s, true)}

Every C->S message is queued and consumed inside the server step; nothing mutates state in a message callback.

## Server to client

| Type | Payload | Notes |
|---|---|---|
${rows(s2c, false)}

"Private" messages are sent to their owner only; no private payload is broadcast.

## Payload types

${named}

## Error codes

\`error {code, msg}\` carries one of these inside a room.

| Code | Name |
|---|---|
${errors}

## Join errors

Every \`joinById\` failure (missing, locked, full, version mismatch, bad name) returns the same error: code ${JOIN_ERROR_CODE}, message "${JOIN_ERROR_MESSAGE}".
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(PROTOCOL_DOC, renderProtocolDoc());
  console.log(`wrote ${PROTOCOL_DOC}`);
}
